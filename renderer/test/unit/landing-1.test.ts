// Frozen before capture: d8f3d1a, generated by the real headless layout/page before production edits.
// Independent expected additions; every other byte stays compared.
function addExpectedMarkers(html: string) {
    return html
        .replace('<div class="bg-primary text-primary-foreground text-xs py-2 px-4"', '<div class="bg-primary text-primary-foreground text-xs py-2 px-4 site-top-bar"')
        .replace('<div class="hidden md:block bg-background/80 backdrop-blur border-b text-sm"', '<div class="hidden md:block bg-background/80 backdrop-blur border-b text-sm site-commerce-bar"')
        .replace('<nav class="border-b bg-background/80 backdrop-blur"', '<nav class="border-b bg-background/80 backdrop-blur site-navbar"')
        .replace(/<footer class="(border-t py-12 bg-muted(?:\/30)?)"/, '<footer class="$1 site-footer"');
}
const NAV_RULE = ".site-top-bar, .site-commerce-bar, .site-navbar { display: none !important; }";
const FOOTER_RULE = ".site-footer { display: none !important; }";
const parse = (html: string) => new DOMParser().parseFromString(html, "text/html");
const rules = (doc: Document) => [...doc.querySelectorAll("style")].map((s) => s.textContent!.trim()).filter(Boolean);
const selectors = (doc: Document) => rules(doc).join("\n").match(/[^{}]+(?=\s*\{)/g)?.map((s) => s.trim()) ?? [];
beforeAll(() => { (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true; });
beforeEach(() => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date("2026-11-26T12:00:00Z"));
    vi.stubEnv("NEXT_PUBLIC_API_URL", "");
});
afterEach(() => { vi.useRealTimers(); vi.unstubAllEnvs(); document.body.innerHTML = ""; });

describe("LANDING-1 — chrome-only page switches", () => {
    for (const kind of Object.keys(cases) as (keyof typeof cases)[]) {
        it(`A1 ${kind}: switches off — only exact root classes differ from the frozen before HTML`, async () => {
            const html = await render(kind);
            expect(html).toBe(addExpectedMarkers(before[kind]));
            expect(rules(parse(html))).toEqual([]);
        });
    }
    for (const [id, hideNav, hideFooter] of [["A2", true, false], ["A3", false, true], ["A4", true, true]] as const) {
        it(`${id}: exact class-only rules, page nav/footer and retained slots are never selected`, async () => {
            vi.stubEnv("NEXT_PUBLIC_API_URL", "https://api.test"); // mocked popup read, no network
            const doc = parse(await render("commerce", hideNav, hideFooter));
            expect(rules(doc).join("\n").replace(/\s+/g, " ")).toBe([...(hideNav ? [NAV_RULE] : []), ...(hideFooter ? [FOOTER_RULE] : [])].join(" "));
            const ss = selectors(doc);
            expect(ss).toEqual([...(hideNav ? [".site-top-bar, .site-commerce-bar, .site-navbar"] : []), ...(hideFooter ? [".site-footer"] : [])]);
            const matched = ss.flatMap((s) => [...doc.querySelectorAll(s)]);
            expect(matched.map((e) => [...e.classList].find((c) => c.startsWith("site-")))).toEqual([
                ...(hideNav ? ["site-top-bar", "site-commerce-bar", "site-navbar"] : []), ...(hideFooter ? ["site-footer"] : []),
            ]);
            for (const id of ["block-nav", "block-footer"]) {
                const blockElement = doc.getElementById(id)!;
                expect(blockElement).not.toBeNull();
                expect(ss.some((s) => blockElement.closest(s))).toBe(false);
            }
            // Positive controls: all chrome roots are sent, even when hidden; all retained slots are present.
            for (const marker of ["site-top-bar", "site-commerce-bar", "site-navbar", "site-footer"]) expect(doc.querySelectorAll("." + marker)).toHaveLength(1);
            for (const name of ["cookie", "popup", "quick-contact"]) {
                const slot = doc.querySelector(`[data-retained="${name}"]`)!;
                expect(slot).not.toBeNull();
                expect(ss.some((s) => slot.closest(s))).toBe(false);
            }
            expect(db.hasActivePopups).toHaveBeenCalledWith("landing-1");
        });
    }
    for (const kind of ["content", "editorial"] as const) {
        it(`A5 ${kind}: absent bars cause no error and do not change either rule`, async () => {
            const doc = parse(await render(kind, true, true));
            expect(rules(doc)[0].replace(/\s+/g, " ")).toBe(NAV_RULE + " " + FOOTER_RULE);
            expect(doc.querySelector(".site-commerce-bar")).toBeNull();
            expect(!!doc.querySelector(".site-top-bar")).toBe(kind === "editorial");
        });
    }
    it("A5: only the top bar absent — the commerce bar remains marked and the hideNav rule is unchanged", async () => {
        const doc = parse(await render("commerce", true, false, { topBar: { show: false } }));
        expect(doc.querySelector(".site-top-bar")).toBeNull();
        expect(doc.querySelectorAll(".site-commerce-bar")).toHaveLength(1);
        expect(rules(doc)).toEqual([NAV_RULE]);
    });
    it("A2: the open mobile menu and desktop dropdown stay inside the marked Navbar root", () => {
        const host = document.createElement("div");
        document.body.appendChild(host);
        const root = createRoot(host);
        try {
            act(() => root.render(createElement(Navbar, {
                siteName: "Test", links: [{ label: "Explore", children: [{ label: "Own link", href: "/own" }] }],
                strings: { navAllOf: "All {label}", navContact: "Contact", navToggleMenu: "Menu", navViewAll: "View all", navContactUs: "Contact us" },
            } as any)));
            const nav = host.querySelector(".site-navbar")!;
            expect(nav.tagName).toBe("NAV");
            act(() => (host.querySelector('[aria-label="Menu"]') as HTMLButtonElement).click());
            const mobile = host.querySelector(".md\\:hidden.absolute")!;
            expect(mobile).not.toBeNull();
            expect(mobile.closest(".site-navbar")).toBe(nav);
            act(() => ([...host.querySelectorAll("button")].find((b) => b.textContent === "Explore")!).click());
            const dropdown = host.querySelector(".absolute.top-full")!;
            expect(dropdown).not.toBeNull();
            expect(dropdown.closest(".site-navbar")).toBe(nav);
        } finally { act(() => root.unmount()); }
    });
});
